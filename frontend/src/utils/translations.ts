// Fill fallbacks for any languages with English
const ALL_CODES: SupportedLangCode[] = ["TE", "GU", "KN", "ML", "PA", "UR"];
ALL_CODES.forEach(code => {
  translations[code] = { ...translations.EN };
});

export function translate(langCode: string | undefined, key: string, fallback?: string): string {
  const code = (langCode?.toUpperCase() || "EN") as SupportedLangCode;
  const dict = translations[code] || translations.EN;
  return dict[key] || translations.EN[key] || fallback || key;
}
